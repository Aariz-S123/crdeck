"""Config loading and data-root paths.

Two data sources share one layout:
- "real":      data/            (official API responses only)
- "synthetic": data/synthetic/  (generated by crdeck.synthetic; every output is labeled SYNTHETIC)

They never mix. Nothing falls back from one to the other.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[2]
CONFIG_DIR = PROJECT_ROOT / "config"
LABELS_DIR = PROJECT_ROOT / "data" / "labels"
CARD_LABELS = LABELS_DIR / "cards.csv"

SOURCES = ("real", "synthetic")


def load_yaml(name: str) -> dict[str, Any]:
    with (CONFIG_DIR / name).open(encoding="utf-8") as f:
        return yaml.safe_load(f)


def model_config() -> dict[str, Any]:
    return load_yaml("model.yaml")


def collection_config() -> dict[str, Any]:
    return load_yaml("collection.yaml")


@dataclass(frozen=True)
class Paths:
    source: str
    root: Path

    @classmethod
    def for_source(cls, source: str | None = None) -> "Paths":
        source = source or os.environ.get("CRDECK_DATA_SOURCE", "real")
        if source not in SOURCES:
            raise ValueError(f"data source must be one of {SOURCES}, got {source!r}")
        root = PROJECT_ROOT / "data" if source == "real" else PROJECT_ROOT / "data" / "synthetic"
        return cls(source=source, root=root)

    @property
    def raw(self) -> Path:
        return self.root / "raw"

    @property
    def interim(self) -> Path:
        return self.root / "interim"

    @property
    def processed(self) -> Path:
        return self.root / "processed"

    @property
    def archetype_labels(self) -> Path:
        return self.root / "labels" / "archetype_labels.csv"

    @property
    def is_synthetic(self) -> bool:
        return self.source == "synthetic"

    def banner(self) -> str:
        if self.is_synthetic:
            return "SYNTHETIC DATA: generated battles for pipeline testing. Not real battles; no result here describes the game."
        return "Real data: official Clash Royale API responses under data/raw."
